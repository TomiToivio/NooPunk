"""The image manifest refuses the things that quietly ruin an art pipeline (#908).

The pipeline's failure mode is not a crash: it is a manifest that disagrees with the directory, and a
screen that renders nothing while everyone assumes the art is "coming later".
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest

import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

import check_image_manifest as checker  # noqa: E402


def _entry(**overrides):
    base = {
        "id": "probe_portrait",
        "category": "placeholders",
        "path": "res://images/placeholders/portrait_probe_3x4.png",
        "subjects": [],
        "location": "test fixture",
        "aspect": "3:4",
        "dimensions": [600, 800],
        "motifs": [],
        "content_warnings": [],
        "prompt": "probe",
        "provenance": "generated by tools/make_placeholder_art.py; abstract geometry only",
        "approved": False,
    }
    base.update(overrides)
    return base


def _validate(assets):
    return checker.validate({"version": 1, "assets": assets}, root=ROOT)


def test_the_shipped_manifest_is_valid():
    manifest = json.loads((ROOT / "images" / "manifest.json").read_text())
    assert checker.validate(manifest, root=ROOT) == []


def test_every_shipped_entry_points_at_a_real_file():
    manifest = json.loads((ROOT / "images" / "manifest.json").read_text())
    for asset in manifest["assets"]:
        path = ROOT / asset["path"].removeprefix("res://")
        assert path.exists(), asset["path"]


def test_a_missing_file_is_caught():
    problems = _validate([_entry(path="res://images/placeholders/nope.png")])
    assert any("file missing" in p for p in problems)


def test_a_duplicate_id_is_caught():
    problems = _validate([_entry(), _entry(path="res://images/placeholders/encounter_probe_4x3.png",
                                           dimensions=[800, 600])])
    assert any("duplicate id" in p for p in problems)


def test_wrong_directory_for_the_class_is_caught():
    problems = _validate([_entry(**{"category": "characters/portraits"})])
    assert any("belongs in characters/portraits/" in p for p in problems)


def test_an_unsnake_case_filename_is_caught():
    entry = _entry(path="res://images/placeholders/Portrait-Probe.png")
    assert any("lowercase snake_case" in p for p in _validate([entry]))


def test_dimensions_must_match_the_file():
    problems = _validate([_entry(dimensions=[601, 800])])
    assert any("declares 601x800" in p for p in problems)


def test_a_sci_fi_motif_without_justification_is_rejected():
    """Early Helsinki is a lived-in 1970s city. An unexplained saucer is a direction error, not a detail."""
    entry = _entry(id="probe_event", **{"category": "events"},
                   path="res://images/placeholders/encounter_probe_4x3.png",
                   dimensions=[800, 600], motifs=["sci_fi"])
    problems = _validate([entry])
    assert any("requires a justification" in p for p in problems)


def test_a_sci_fi_motif_with_a_justification_is_accepted():
    entry = _entry(id="probe_event", **{"category": "events"},
                   path="res://images/events/event_probe_4x3.png",
                   dimensions=[800, 600], motifs=["sci_fi"],
                   justification="the scene is the anomaly itself")
    assert _validate([entry]) == []


def test_sci_fi_background_is_refused_outside_events():
    entry = _entry(**{"category": "locations"}, path="res://images/placeholders/location_probe_16x9.png",
                   dimensions=[960, 540], motifs=["sci_fi"],
                   justification="someone wanted a spaceship behind a street corner")
    problems = _validate([entry])
    assert any("belongs to an events asset" in p for p in problems)


def test_a_placeholder_cannot_be_approved_art():
    problems = _validate([_entry(approved=True)])
    assert any("placeholder cannot be approved" in p for p in problems)


def test_provenance_is_mandatory():
    problems = _validate([_entry(provenance="   ")])
    assert any("empty provenance" in p for p in problems)


def test_a_manifest_without_assets_is_rejected():
    assert checker.validate({"assets": []}, root=ROOT) == ["manifest has no assets list"]


@pytest.mark.parametrize("field", ["id", "category", "path", "provenance", "dimensions"])
def test_required_fields_are_required(field):
    entry = _entry()
    del entry[field]
    problems = _validate([entry])
    assert any(f"missing {field}" in p for p in problems)
