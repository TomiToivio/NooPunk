#!/usr/bin/env python3
"""SWN coverage audit (#1105): verify every claim in `data/rules/swn_traceability.json`.

The CWN audit (`tools/cwn_parity_audit.py`) established the shape: a curated register is worthless if it is
the only place a claim is checked, so this tool re-verifies each row against the tree — the module exists,
the *named* procedure/class/constant exists in that module's AST, the cited test exists and references the
module, the rulebook anchor exists, and the cited section exists in the extracted Deluxe index with the
stated printed page. Status is then recomputed from that evidence instead of trusted from the file.

    python3 tools/swn_parity_audit.py            # regenerate the report
    python3 tools/swn_parity_audit.py --check    # exit 1 if the committed report is stale or evidence fails
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

from cwn_parity_audit import verify_entry  # noqa: E402  (one evidence checker, not two)

REGISTER = ROOT / "data" / "rules" / "swn_traceability.json"
SECTIONS = ROOT / "data" / "rules" / "swn_sections.json"
REPORT = ROOT / "docs" / "rules" / "SWN_COVERAGE_1105.md"

STATUSES = ("verified", "verified_reuse", "partial", "unverified", "missing", "not_applicable")
#: Statuses that claim code exists, and therefore require evidence.
EVIDENCED = {"verified", "verified_reuse", "partial"}


def build() -> dict:
    register = json.loads(REGISTER.read_text(encoding="utf-8"))
    sections = {s["id"]: s for s in json.loads(SECTIONS.read_text(encoding="utf-8"))["sections"]}

    rows: list[dict] = []
    for entry in register["rows"]:
        checked = verify_entry(entry)
        problems: list[str] = list(checked["problems"])
        section = sections.get(entry["id"])
        if section is None:
            problems.append(f"section {entry['id']!r} is not in data/rules/swn_sections.json")
        elif section["first_page"] != entry["page"]:
            problems.append(f"{entry['id']}: register says p.{entry['page']}, the book's running head says "
                            f"p.{section['first_page']}")
        if entry["status"] in EVIDENCED and not (entry.get("modules") and entry.get("tests")):
            problems.append("status claims implementation but names no module and test")
        if entry["status"] not in EVIDENCED and entry.get("modules"):
            problems.append("a non-implemented status must not cite modules")
        if entry["status"] not in STATUSES:
            problems.append(f"unknown status {entry['status']!r}")

        row = dict(entry)
        row["problems"] = problems
        # A status is only as good as its evidence: a broken citation demotes the claim, it does not pass.
        row["effective"] = "unverified" if problems and row["status"] in EVIDENCED else row["status"]
        rows.append(row)

    counts = {status: sum(1 for row in rows if row["effective"] == status) for status in STATUSES}
    return {
        "issue": 1105,
        "source": register["source"],
        "rows": sorted(rows, key=lambda row: (row["page"], row["id"])),
        "counts": counts,
        "problems": {row["id"]: row["problems"] for row in rows if row["problems"]},
    }


def render(matrix: dict) -> str:
    counts = matrix["counts"]
    total = len(matrix["rows"])
    lines = [
        "# SWN coverage report (#1105)",
        "",
        "Generated by `tools/swn_parity_audit.py` from `data/rules/swn_traceability.json` — do not edit by hand.",
        "",
        "This is the **section-level** view of the book (one row per printed section). The **chapter-level**",
        "tracker view — the issue's A–K checklist, one row per subsystem — is",
        "[SWN_COVERAGE_1105.md](SWN_COVERAGE_1105.md), generated from `data/rules/wwn_register.json`. The two",
        "disagree on purpose: the subsystem view asks \"is this piece of the tracker done?\", this one asks",
        "\"is this heading in the book implemented?\".",
        "",
        f"**{total} sections of Stars Without Number Revised Deluxe**, extracted from the book's own",
        "running heads (`data/rules/swn_sections.json`). Every row cites a printed page that exists in that",
        "index; a row whose evidence fails is demoted to `unverified` rather than trusted.",
        "",
        f"- verified **{counts['verified']}** · verified reuse **{counts['verified_reuse']}** · "
        f"partial **{counts['partial']}**",
        f"- unverified **{counts['unverified']}** · missing **{counts['missing']}** · "
        f"not applicable **{counts['not_applicable']}**",
        "",
        "Read the statuses as answers to *\"is this playable WWN rule implemented here?\"*, not as a quality",
        "score: `missing` is the honest answer for most of the book today, and the register exists so nobody",
        "can mistake a chapter heading for coverage.",
        "",
        "## Status definitions",
        "",
    ]
    for name, meaning in json.loads(REGISTER.read_text(encoding="utf-8"))["statuses"].items():
        lines.append(f"- **{name}** — {meaning}")
    lines += ["", "## Implemented, reused or partial", "",
              "| § | printed page | section | status | evidence |",
              "|---|---|---|---|---|"]
    for row in matrix["rows"]:
        if row["effective"] not in EVIDENCED:
            continue
        evidence = ", ".join(f"`{spec['path']}` ({', '.join(spec['procedures'])})"
                             for spec in row.get("modules", [])) or "—"
        lines.append(f"| {row['id']} | p.{row['page']} | {row['title']} | {row['effective']} | {evidence} |")
    lines += ["", "## Gaps, with the reason recorded", "",
              "| § | printed page | section | status | why |", "|---|---|---|---|---|"]
    for row in matrix["rows"]:
        if row["effective"] in EVIDENCED:
            continue
        note = row["note"].replace("|", "/")
        lines.append(f"| {row['id']} | p.{row['page']} | {row['title']} | {row['effective']} | {note} |")

    if matrix["problems"]:
        lines += ["", "## Evidence that does not verify", ""]
        for key, problems in matrix["problems"].items():
            lines.append(f"- `{key}`: " + "; ".join(problems))
    lines += [
        "",
        "## What this report does not claim",
        "",
        "* It does not claim SWN's power text is reproduced. SWN has no verified SRD licence, so the register",
        "  records page numbers and NoöPunk-authored technique ids, never the book's ability text.",
        "* It does not reproduce book text, tables or page images. The PDF is the author's authorised copy, "
        "is not in the repository, and is not redistributable.",
        "* A `verified_reuse` row means one resolver serves both games **and a test pins the WWN numbers**. "
        "Where that test does not exist, the row says `unverified` — see saving throws.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)

    matrix = build()
    text = render(matrix)
    if args.check:
        stale = (not REPORT.is_file() or REPORT.read_text(encoding="utf-8") != text)
        if stale:
            print("swn_parity_audit: report is stale; run python3 tools/swn_parity_audit.py", file=sys.stderr)
            return 1
        if matrix["problems"]:
            print(f"swn_parity_audit: {len(matrix['problems'])} row(s) do not verify", file=sys.stderr)
            for key, problems in matrix["problems"].items():
                print(f"  {key}: {'; '.join(problems)}", file=sys.stderr)
            return 1
        print(f"swn_parity_audit: up to date ({len(matrix['rows'])} sections)")
        return 0

    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(text, encoding="utf-8")
    counts = matrix["counts"]
    print(f"swn_parity_audit: {len(matrix['rows'])} sections -> {REPORT.relative_to(ROOT)}")
    print("  " + " ".join(f"{name}={counts[name]}" for name in STATUSES))
    if matrix["problems"]:
        print(f"  {len(matrix['problems'])} row(s) do not verify", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
