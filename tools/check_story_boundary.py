"""The Story/ boundary, as a check an agent can run before committing (#1295).

The rule is simple and absolute: `NooPunk-Story/Story/` is Tomi's manuscript. Agents read it and never write it.
A rule that cannot fail is a wish, so this tool has two modes:

* ``--check``  — static: the subprojects exist, `Story/` holds only authorable text and its policy, and no
  generated-artefact marker appears anywhere inside it.
* ``--changed`` — compare against ``origin/main`` and fail if anything under ``Story/`` differs, unless
  ``NOOPUNK_STORY_HUMAN_AUTHOR=1`` is set in the environment. Only a human session should set that.

Neither mode can prove who wrote a file. They make the default path a refusal and the escape hatch deliberate,
which is the most a repository check can honestly do.
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STORY = ROOT / "NooPunk-Story" / "Story"
SUBPROJECTS = ("NooPunk-Story", "NooPunk-Simulator", "NooPunk-RPG")

#: Files that may exist in Story/ without being manuscript. The policy page is the only one.
ALLOWED_NON_MANUSCRIPT = {"POLICY.md", ".gitkeep"}
MANUSCRIPT_SUFFIXES = {".md", ".txt", ".markdown"}
GENERATED_MARKERS = ("<!-- generated", "agent-generated", "autogenerated by", "do not edit; generated")


def static_problems() -> list[str]:
    problems: list[str] = []
    for name in SUBPROJECTS:
        path = ROOT / name
        if not path.is_dir():
            problems.append(f"missing subproject directory {name}/")
            continue
        if not (path / "README.md").is_file():
            problems.append(f"{name}/ has no README.md stating its purpose and ownership")
    if not STORY.is_dir():
        problems.append("NooPunk-Story/Story/ does not exist")
        return problems
    if not (STORY / "POLICY.md").is_file():
        problems.append("NooPunk-Story/Story/POLICY.md is missing; the boundary must be written down")
    for path in sorted(STORY.rglob("*")):
        if path.is_dir():
            continue
        rel = path.relative_to(STORY).as_posix()
        if rel in ALLOWED_NON_MANUSCRIPT:
            continue
        if path.suffix.lower() not in MANUSCRIPT_SUFFIXES:
            problems.append(f"Story/{rel}: {path.suffix or 'no extension'} is not a manuscript format")
            continue
        text = path.read_text(encoding="utf-8", errors="replace").lower()
        for marker in GENERATED_MARKERS:
            if marker in text:
                problems.append(f"Story/{rel}: contains the generated-artefact marker {marker!r}")
    return problems


def changed_story_files(base: str = "origin/main") -> list[str]:
    changed: set[str] = set()
    for command in (
        ["git", "diff", "--name-only", base, "--", "NooPunk-Story/Story"],
        # An agent's first mistake is usually a new file, which `git diff` does not show.
        ["git", "ls-files", "--others", "--exclude-standard", "--", "NooPunk-Story/Story"],
    ):
        result = subprocess.run(command, cwd=ROOT, capture_output=True, text=True)
        if result.returncode != 0:
            raise SystemExit(f"{' '.join(command[:2])} failed: {result.stderr.strip()}")
        changed.update(line for line in result.stdout.splitlines() if line.strip())
    return sorted(changed)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="static layout and marker check")
    parser.add_argument("--changed", action="store_true", help="refuse Story/ changes without human authorisation")
    parser.add_argument("--base", default="origin/main")
    args = parser.parse_args(argv)

    if not args.check and not args.changed:
        parser.error("choose --check or --changed")

    failed = False
    if args.check:
        problems = static_problems()
        for problem in problems:
            print(f"FAIL: {problem}", file=sys.stderr)
        failed = failed or bool(problems)
        if not problems:
            print("OK: subprojects present; Story/ holds manuscript text and its policy only")

    if args.changed:
        try:
            changed = changed_story_files(args.base)
        except SystemExit as exc:
            print(f"FAIL: {exc}", file=sys.stderr)
            return 2
        if changed and os.environ.get("NOOPUNK_STORY_HUMAN_AUTHOR") != "1":
            for path in changed:
                print(f"FAIL: {path} changed, but Story/ is human-only", file=sys.stderr)
            print(
                "If a human is making this change, set NOOPUNK_STORY_HUMAN_AUTHOR=1. "
                "An agent must revert the change and write a review note in Graph/ instead.",
                file=sys.stderr,
            )
            failed = True
        elif not changed:
            print("OK: no manuscript changes")

    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
