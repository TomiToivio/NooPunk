#!/usr/bin/env python3
"""Render the #1113 chronology table from `data/world/chronology_1113.json`.

The chronology is data. The canon document shows a table of it, and a table typed by hand beside a JSON file is
two sources of truth waiting to disagree. This prints the table so the document can carry exactly what the data
says.

It deliberately does **not** check the document against the output. `AGENTS.md` forbids documentation gates and
text-matching assertions over prose, and a table that is regenerated by hand once is enough; the JSON is
authoritative either way.

Usage:
    python3 tools/chronology_1113_render.py            # print the markdown table
    python3 tools/chronology_1113_render.py --write    # rewrite the table inside the canon document
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data" / "world" / "chronology_1113.json"
DOC = ROOT / "docs" / "world" / "CANON_FORTRESS_EUROPE_1113.md"

#: The markers the document and the data share. Display form for the table.
LABELS = {"canon": "CANON", "in_world_claim": "IN-WORLD CLAIM", "open": "OPEN"}

BEGIN = "<!-- chronology-table:begin -->"
END = "<!-- chronology-table:end -->"


def render_table() -> str:
    data = json.loads(DATA.read_text(encoding="utf-8"))
    events = sorted(data["events"], key=lambda event: event["order"])
    lines = ["| # | When | Event | Status |", "|---:|---|---|---|"]
    for event in events:
        label = LABELS.get(event["status"], event["status"].upper())
        lines.append(f"| {event['order']} | {event['when'] or '—'} | {event['title']} | {label} |")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write", action="store_true", help="rewrite the table inside the canon document")
    args = parser.parse_args(argv)

    table = render_table()
    if not args.write:
        print(table)
        return 0

    text = DOC.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        print(f"chronology_1113_render: the document has no {BEGIN} / {END} markers")
        return 1
    updated = re.sub(
        re.escape(BEGIN) + r".*?" + re.escape(END),
        f"{BEGIN}\n{table}\n{END}",
        text,
        flags=re.DOTALL,
    )
    if updated == text:
        print("chronology_1113_render: document already up to date")
        return 0
    DOC.write_text(updated, encoding="utf-8")
    print(f"chronology_1113_render: table rewritten in {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
